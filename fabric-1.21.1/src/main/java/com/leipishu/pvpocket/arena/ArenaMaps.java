package com.leipishu.pvpocket.arena;

import com.leipishu.pvpocket.PvPocket;

import java.util.List;

/**
 * The map list the rule panel cycles through.
 *
 * <p>Index order is part of the wire format: {@code e.template} is stored as an enum value, so
 * reordering this list changes the meaning of every saved rule set. Append, never insert.</p>
 *
 * <p><b>This list was compacted once, on purpose.</b> 试炼密室 / 蓟桥 / 阿瓦隆 were withdrawn, and
 * rather than leave three dead slots in the panel they were removed outright — which shifts every
 * index after them. The cost is that a rule set saved before the change (a session recovered after a
 * crash, and nothing else: rules live for the length of one duel) now resolves to a different map.
 * That is a wrong arena, not a crash, and the alternative was three unusable entries in a cycle
 * control. If a map is ever withdrawn again after a release, leave a hole instead.</p>
 *
 * <p>Every map here is converted from a world save with {@code scripts/world2struct.py}, and every
 * one is third-party artwork under <b>CC BY-SA 4.0</b>. See {@code THIRD-PARTY-NOTICES.md} at the
 * repository root for the attribution and the licence terms that redistribution carries. Do not add
 * a map here whose licence has not been checked: the arena files ship inside the jar, so an
 * unlicensed map is redistribution, not fair use.</p>
 *
 * <p>Sizes are the template bounding boxes as produced by the converter, not hand-written guesses.
 * {@link ArenaMap#paste} re-checks them against the loaded template and logs a warning on a
 * mismatch, but a mismatch here also means the rule panel has been laying out a plot that is the
 * wrong size.</p>
 */
public final class ArenaMaps {

    /**
     * Indoor quartz arena. 38k blocks, enclosed on all four sides, so the boundary curtain sits on
     * real walls rather than in mid-air.
     */
    public static final ArenaMap FUN_HOUSE = new ArenaMap("arena_fun_house", "游乐屋",
            PvPocket.id("arena_fun_house"), 82, 28, 57);

    /**
     * A floating island disc with a rim of terracotta and a ring of lamps. The smallest map here
     * (7k blocks) and the only one you can fall out of: past the rim there is nothing, so the edge
     * of the build is the arena boundary rather than a wall. Source XML spawns at
     * {@code x=+-17, z=1.5}, across the short axis, so the two sides face along X.
     */
    public static final ArenaMap EARTHBORN = new ArenaMap("arena_earthborn", "浮岛",
            PvPocket.id("arena_earthborn"), 45, 34, 60);

    /**
     * Enclosed space station: corridors, two decks and a hole in the middle. 26 distinct block
     * names, the flattest palette of the set, so it reads as clean geometry rather than as terrain.
     * Source spawns at {@code x=0.5, z=+-37}, along Z like the rest of the arcade maps.
     */
    public static final ArenaMap DARK_NEBULA = new ArenaMap("arena_dark_nebula", "暗星云",
            PvPocket.id("arena_dark_nebula"), 87, 43, 79, true);

    /**
     * A western town street: 60k blocks, 94 block names, the densest map here after the trial
     * chambers. The source XML spreads ten spawn points around the town rather than giving two
     * team ends; the street runs along X (mine entrance to sheriff's office), so that is the axis
     * the pads are placed on.
     */
    public static final ArenaMap DEADWOOD = new ArenaMap("arena_deadwood", "枯木镇",
            PvPocket.id("arena_deadwood"), 88, 36, 87);

    /**
     * The amphitheatre. Generated by {@code scripts/colosseum.py} rather than converted, because
     * no redistributable colosseum turned up: it is the largest map here at 147x119 and the only
     * one that is ours outright. Two gates on the X axis, ten rows of seating, a 15-block outer
     * wall. It is also the only map whose two ends are a design decision instead of an observation
     * about somebody else's spawn XML.
     */
    public static final ArenaMap COLOSSEUM = new ArenaMap("arena_colosseum", "斗兽场",
            PvPocket.id("arena_colosseum"), 147, 29, 119);

    public static final List<ArenaMap> ALL = List.of(ArenaMap.FLAT, FUN_HOUSE, EARTHBORN,
            DARK_NEBULA, DEADWOOD, COLOSSEUM);

    private ArenaMaps() {
    }

    /** Index-safe lookup: an out-of-range value (older or newer client) falls back to flat. */
    public static ArenaMap byIndex(int index) {
        if (index < 0 || index >= ALL.size()) {
            return ArenaMap.FLAT;
        }
        return ALL.get(index);
    }

    public static String[] labels() {
        String[] out = new String[ALL.size()];
        for (int i = 0; i < out.length; i++) {
            out[i] = ALL.get(i).label;
        }
        return out;
    }
}
